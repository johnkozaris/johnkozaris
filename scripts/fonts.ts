// Turns the subset fonts in fonts/ into base64 strings that SVGs can embed.
export {};
// Run once when the font set changes: bun scripts/fonts.ts
const names = ["inter-400", "inter-500", "inter-600", "mono-400"] as const;
let out = "// Generated by scripts/fonts.ts from fonts/*.woff2. Inter and JetBrains Mono, SIL OFL 1.1.\n";
for (const name of names) {
  const bytes = await Bun.file(`fonts/${name}.woff2`).bytes();
  const id = name.toUpperCase().replace("-", "_");
  out += `export const ${id} = "${Buffer.from(bytes).toString("base64")}";\n`;
}
await Bun.write("shared/fonts.generated.ts", out);
console.log("wrote shared/fonts.generated.ts", out.length, "chars");
