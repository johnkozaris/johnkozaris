// Writes advance widths of the embedded fonts, so the Worker can lay out text without fontkit.
// Run when the font set changes: bun scripts/metrics.ts
import * as fontkit from "fontkit";

const faces = ["inter-400", "inter-500", "inter-600", "mono-400"] as const;
const chars = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join("") + "·–—’“”…×↑↓−";
const out: Record<string, Record<string, number>> = {};
for (const face of faces) {
  const f: any = fontkit.openSync(new URL(`../fonts/${face}.woff2`, import.meta.url).pathname);
  out[face] = {};
  for (const c of chars) out[face][c] = Math.round((f.layout(c).advanceWidth * 1000) / f.unitsPerEm);
}
await Bun.write(
  new URL("../shared/metrics.generated.ts", import.meta.url).pathname,
  `// Generated by scripts/metrics.ts: advance width per character, in thousandths of an em.\nexport const ADVANCE: Record<string, Record<string, number>> = ${JSON.stringify(out)};\n`,
);
console.log("wrote shared/metrics.generated.ts");
